// Subagent Bash calls in flight or recently done. Two agents' calls that overlap
// both see each other's files in their snapshots: a file in both goes to the
// shorter call, since a long test run rarely makes what a quick command made.
let windows: BashWindow[] = []
const WINDOW_KEEP_MS = 10 * 60_000

// The working tree's status where the session runs, or null outside git.
// `git` runs in the session's directory unless told otherwise.
async function snapshot($: EngineInterface): Promise<Snapshot | null> {
  const top = await $.process.run(['git', 'rev-parse', '--show-toplevel'], { timeoutMs: 5000 })
  const root = top.exitCode === 0 ? top.stdout.trim() : ''
  if (!root) return null
  const r = await $.process.run(['git', 'status', '--porcelain=v1', '-z', '--untracked-files=all'], { cwd: root, timeoutMs: 5000 })
  if (r.exitCode !== 0 || r.isStdoutTruncated) return null
  return { root, status: parseStatus(r.stdout) }
}

// The file operations a finished tool call made: Write says whether it created
// the file; edits name their file; Bash is read for rm and mv.
function fileOps(e: { tool: string } & Record<string, unknown>, result: unknown): FileOp[] {
  const r = (result ?? {}) as Record<string, unknown>
  const path = (v: unknown): string => (typeof v === 'string' ? v : '')
  if (e.tool === 'Write') {
    const p = path(r.filePath) || path(e.file_path)
    return p ? [{ path: p, op: r.type === 'update' ? 'edit' : 'new' }] : []
  }
  if (e.tool === 'Edit' || e.tool === 'MultiEdit' || e.tool === 'NotebookEdit') {
    const p = path(r.filePath) || path(e.file_path) || path(e.notebook_path)
    return p ? [{ path: p, op: 'edit' }] : []
  }
  if (e.tool === 'Bash' && typeof e.command === 'string') return bashOps(e.command)
  return []
}

// Records a finished call's file operations on its agent's lab table.
async function recordFiles($: EngineInterface, e: ToolCallInput, done: ToolCallResult, before: Snapshot | null, start: number, key: string): Promise<ToolCallResult> {
  const agentId = e.agentId
  const isBash = agentId !== undefined && e.tool === 'Bash'
  if (!agentId || ('deny' in done && done.deny !== undefined)) return done
  // A failed Bash may still have changed files; a failed Write or Edit did not.
  if (done.isError && !isBash) return done
  // Drawing only: a failure here must never touch the tool's own result.
  try {
    const call = e as unknown as { tool: string } & Record<string, unknown>
    let ops: FileOp[]
    if (isBash) {
      const after = before ? await snapshot($) : null
      if (before && after && before.root === after.root) {
        const diff = statusOps(before.status, after.status)
        const gone: FileOp[] = []
        for (const path of diff.vanished) if (!(await $.fs.exists(`${after.root}/${path}`))) gone.push({ path, op: 'gone' })
        ops = [...diff.ops, ...gone].map(op => ({ ...op, path: `${after.root}/${op.path}` }))
        // A file another agent wrote or edited while this command ran is theirs.
        const list = await read($, agents)
        const theirs = new Set(list.filter(a => a.agentId !== agentId).flatMap(a => (a.files ?? []).filter(f => f.at >= start).map(f => f.path)))
        ops = ops.filter(op => !theirs.has(op.path))
        // Against other agents' overlapping Bash calls, the shorter call keeps a shared file.
        const end = await $.clock.now()
        const claim = claimOps(windows, key, agentId, start, end, ops, typeof call.command === 'string' ? call.command : undefined)
        ops = claim.ops
        const stolen = claim.stolen
        if (stolen.size) {
          await update($, agents, all =>
            all.map(a => {
              const paths = a.agentId ? stolen.get(a.agentId) : undefined
              return paths ? { ...a, files: (a.files ?? []).filter(f => !paths.has(f.path)) } : a
            }),
          )
        }
      } else {
        ops = typeof call.command === 'string' ? bashOps(call.command) : []
      }
    } else {
      ops = fileOps(call, done.result)
    }
    if (ops.length === 0) return done
    const at = await $.clock.now()
    await update($, agents, list => list.map(a => (a.agentId === agentId ? { ...a, files: applyOps(a.files, ops, at) } : a)))
    await update($, now, () => at)
  } catch {
    // The table misses this call's files; the call stands.
  }
  return done
}

